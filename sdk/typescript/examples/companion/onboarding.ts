/**
 * 首次见面的几条话：先说清小丑鱼现在真能做什么，再给三件今天就能开始的事。
 *
 * 三件事做成快捷回复，点一下就以用户的口吻发出去，所以每一件都必须是聊天里真能办到的
 * （目标、构件、事项各有工具）；"帮我盯着"只能在设置里配，只在文字里指路，不放进选项。
 */
export const ONBOARDING_STARTERS = ["帮我定一个目标", "做一个能勾选的待办清单", "帮我记一件要跟进的事"] as const;

export function onboardingMessages(name: string): string[] {
  return [
    `${name}，你好，我是小丑鱼。`,
    "我能陪你聊，也能动手：把一个目标聊清楚后帮你记着、到点问问进度；做能直接用的小工具，比如清单、计时器、计算器；记下要跟进的事，到时间提醒你。",
    "总览里会有按你关心的话题写的动态，技能库里有我想到能帮你做的点子；想让我隔一段时间联网看一眼某件事，在设置的「提醒与后台」里写下来就行。",
    "你的偏好、目标和做出来的东西都存在这台电脑上，随时能查看、修正或删掉。想给我换个名字，点上方的「活动」，在「身份」里改。",
    `今天可以先从这几件里挑一件，或者直接说你想做的事：\n【选项】${ONBOARDING_STARTERS.join("｜")}`,
  ];
}
