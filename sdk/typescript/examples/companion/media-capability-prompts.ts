/**
 * 自媒体两项能力的提示词：选题评估与短视频脚本。
 *
 * 单独成文件的理由：`capabilities.ts` 已近 3000 行，而这两条提示要写出必需小节，
 * 比一句话长得多。既有的 `imagePromptCapabilityPrompt()` 是同一处理。
 *
 * 设计见 docs/media-capabilities-program-design-2026-09-08.md。两条约束是硬的：
 *
 * 1. **不声称掌握实时热度**。小丑鱼不抓平台热搜榜（[决定](docs/easel-studio-program-design-2026-09-08.md)），
 *    因为抓取失效时会安静地给出空榜或过时榜，用户看不出区别。所以选题评估说的是
 *    "这类题材通常"，不是"当前热度高"——除非材料里真的带了数据。
 * 2. **四项参数缺失时不猜着写完就算**。假设要写进产物，并由交付物待确认追问收进元数据，
 *    能力页显示「N 处待你确认」。这是复用而不是新建机制。
 */

/**
 * 脚本与选题都依赖的四项参数。
 *
 * 能力的执行入口只有目标 + 材料 + 格式，没有结构化参数位（`inputTemplate` 是
 * bot-market 模板的机制，不是能力的），所以这四项走提示 + 待确认，而不是新增表单。
 * 守卫测试钉住这个清单被两条提示同时引用——清单改了而提示没跟着改，就会出现
 * 一条谁都不检查的参数。
 */
export const MEDIA_REQUIRED_PARAMETERS = ["平台", "时长", "受众", "目标"] as const;

/** 缺参数时的统一处理：不猜着蒙过去，也不停下来不干活。 */
function parameterBlock(): string {
  return [
    `必须先明确四项参数：${MEDIA_REQUIRED_PARAMETERS.join("、")}。`,
    "用户没有给的参数不要含糊带过：按该平台的常见做法取一个具体值继续做完，",
    "并在产物末尾的「参数假设」小节逐项写明用了什么值、哪些是你假设的。",
    "不要因为参数不全就只交回一串问题——先做完，再把假设列出来。",
  ].join("\n");
}

/** 两条提示共用的事实边界。 */
function realtimeBoundary(): string {
  return [
    "禁止声称掌握实时热度、平台流量、播放量或排行榜数据。",
    "材料里没有带时间的数据支撑时，只能写「这类题材通常……」这样的一般判断，",
    "不能写「当前热度高」「正在涨」「平台在推」。",
    "材料里确实带了数据时，引用它并写出数据的时间。",
  ].join("\n");
}

/**
 * 选题评估。
 *
 * 输入是一批候选选题——用户自己给的，或「深度研究」「市场机会」的产出。
 * 这个能力不负责找选题，只负责判断哪些值得做。
 */
export function topicEvaluationPrompt(): string {
  return [
    "把用户提供的候选选题排出优先级，逐条给出可执行的判断。",
    "",
    "输入是一批候选选题（用户自己列的，或由「深度研究」「市场机会」产出）。",
    "你不负责去找新选题；材料里只有一个候选时就评估这一个，不要自行凑数。",
    "",
    "每条候选都要写清：",
    "1. 判断：做 / 不做 / 改造后做——三者必选其一，不要写「可以考虑」。",
    "2. 理由：为什么是这个判断，落到具体的受众处境或内容形态上。",
    "3. 目标受众：谁会看，他们看之前已经知道什么。",
    "4. 预计难点：素材、专业门槛、拍摄成本、同类内容已经很多，写实际会卡住的那一项。",
    "5. 判断为「不做」时，写清放弃的原因；「改造后做」时，写清改造成什么。",
    "",
    "最后给出排序，并把排序依据写成一句话（不能只给序号）。",
    "",
    realtimeBoundary(),
    "",
    parameterBlock(),
  ].join("\n");
}

/**
 * 短视频脚本。
 *
 * 开头备选放在这里而不是单列一个「钩子」能力：一段钩子几十个字，按工具策略
 * "短答复、判断、复述不是产物"，为它单独造文件和任务不合适。
 */
export function videoScriptPrompt(): string {
  return [
    "把一个选题写成可以直接开拍的脚本。",
    "",
    "必需的四部分，缺一不可：",
    "1. 开头：给 3 个备选，各一句到两句，走不同路子（提问 / 结论前置 / 反常识）。",
    "   逐条注明它赌的是观众的哪种反应。",
    "2. 分段：每段写时间轴（如 0:00-0:08）、口播原文、画面提示。",
    "   口播要写成可以照读的话，不是要点提纲；画面提示写拍什么，不写运镜术语堆砌。",
    "3. 结尾动作：只列一个（关注 / 评论 / 跳转），并写清为什么是这一个。",
    "4. 参数假设：见下。",
    "",
    "时间轴总长必须与设定的时长一致；对不上就调整分段，不要留一段没有时间的内容。",
    "",
    realtimeBoundary(),
    "",
    parameterBlock(),
  ].join("\n");
}
